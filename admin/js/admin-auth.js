/**
 * Admin Authentication (admin-auth.js)
 * ------------------------------------------------------------
 * Handles staff sign-in for the admin panel using AWS Cognito's Hosted UI
 * with Google as the identity provider (OAuth 2.0 "authorization code" flow).
 *
 * How sign-in works:
 *   1. Staff clicks "Sign in with Google" on /admin/index.html
 *   2. We redirect to Cognito, which hands off to Google
 *   3. Google → Cognito → back to /admin/index.html?code=...&state=...
 *   4. We check `state` matches what we sent (CSRF protection),
 *      then trade the `code` for tokens at Cognito's /oauth2/token endpoint
 *   5. The id_token (a JWT) is stored in localStorage and sent as
 *      "Authorization: Bearer <token>" on every API call
 *   6. API Gateway verifies the JWT signature before the Lambda ever runs
 *
 * Note: the expiry check below only decides whether to show the page or
 * bounce to login. Real security is enforced server-side by API Gateway.
 *
 * Exposes a global `AdminAuth` object used by every editor script.
 */

const AdminAuth = {
  // Values come from admin-config.js (generated by setup.sh). Getters let this
  // file load even if the config is missing, falling back to safe defaults.
  get clientId() { return (typeof ADMIN_CONFIG !== 'undefined' && ADMIN_CONFIG.cognitoClientId) || ''; },
  get redirectUri() { return (typeof ADMIN_CONFIG !== 'undefined' && ADMIN_CONFIG.callbackUrl) || ''; },
  get cognitoDomain() { return (typeof ADMIN_CONFIG !== 'undefined' && ADMIN_CONFIG.cognitoDomain) || ''; },
  get apiEndpoint() { return (typeof ADMIN_CONFIG !== 'undefined' && ADMIN_CONFIG.apiEndpoint) || '/admin/api'; },
  get devMode() { return typeof ADMIN_CONFIG !== 'undefined' && ADMIN_CONFIG.devMode === true; },

  responseType: 'code',
  scope: 'openid email profile',

  TOKEN_KEY: 'admin_token',
  STATE_KEY: 'admin_oauth_state',

  // Runs on every admin page load: decides between "show login" and "show page".
  init() {
    const path = window.location.pathname;
    const token = this.getToken();
    const isLoginPage = path.includes('/admin/index.html') || path.endsWith('/admin/');

    // Dev mode (local preview): skip auth entirely and show a placeholder user.
    if (this.devMode) {
      if (!isLoginPage) this.setupAdminPage('preview@serenityspa.com');
      return;
    }

    if (isLoginPage) {
      // Already signed in? Skip the login screen.
      if (token && this.isTokenValid(token)) {
        window.location.href = './dashboard.html';
        return;
      }
      this.setupLoginPage();
    } else if (path.includes('/admin/')) {
      // Protected page: no valid token → back to login.
      if (!token || !this.isTokenValid(token)) {
        window.location.href = './index.html';
      } else {
        this.setupAdminPage();
      }
    }
  },

  getToken() {
    return localStorage.getItem(this.TOKEN_KEY);
  },

  setToken(token) {
    localStorage.setItem(this.TOKEN_KEY, token);
  },

  // Read the middle (payload) segment of a JWT.
  // JWTs use base64url encoding ('-' and '_', no padding), which plain atob()
  // can't always decode — so convert to standard base64 first.
  decodeJwtPayload(token) {
    try {
      const base64url = token.split('.')[1];
      const base64 = base64url.replace(/-/g, '+').replace(/_/g, '/')
        .padEnd(Math.ceil(base64url.length / 4) * 4, '=');
      return JSON.parse(atob(base64));
    } catch (e) {
      return null;
    }
  },

  // Client-side expiry check only (UX convenience — the server re-verifies).
  isTokenValid(token) {
    const payload = token && this.decodeJwtPayload(token);
    return !!(payload && payload.exp && Date.now() < payload.exp * 1000);
  },

  getUserInfo() {
    const token = this.getToken();
    return token ? this.decodeJwtPayload(token) : null;
  },

  setupLoginPage() {
    const googleBtn = document.getElementById('google-signin-btn');
    if (googleBtn) {
      googleBtn.addEventListener('click', () => this.initiateGoogleOAuth());
    }
    // If Cognito just redirected back here with ?code=..., finish the sign-in.
    this.handleAuthCallback();
  },

  // Show the signed-in email in the header and wire up the logout button.
  setupAdminPage(devEmail = null) {
    const userInfo = this.getUserInfo();
    const userEmailEl = document.getElementById('user-email');
    const logoutBtn = document.getElementById('logout-btn');

    if (userEmailEl) {
      userEmailEl.textContent = devEmail || userInfo?.email || 'Admin User';
    }

    if (logoutBtn) {
      logoutBtn.addEventListener('click', () => {
        if (this.devMode) return;
        this.logout();
      });
    }
  },

  // Step 2: send the browser to Cognito's Hosted UI, going straight to Google.
  initiateGoogleOAuth() {
    // Random `state` value, remembered for this tab. Cognito echoes it back,
    // and we only accept a callback whose state matches (prevents login CSRF).
    const state = crypto.randomUUID();
    sessionStorage.setItem(this.STATE_KEY, state);

    const params = new URLSearchParams({
      client_id: this.clientId,
      redirect_uri: this.redirectUri,
      response_type: this.responseType,
      scope: this.scope,
      identity_provider: 'Google',
      state
    });

    window.location.href = `https://${this.cognitoDomain}/oauth2/authorize?${params.toString()}`;
  },

  // Step 3/4: we've been redirected back with ?code=...&state=...
  handleAuthCallback() {
    const params = new URLSearchParams(window.location.search);
    const code = params.get('code');
    if (!code) return;

    const messageEl = document.getElementById('auth-message');
    const expectedState = sessionStorage.getItem(this.STATE_KEY);
    sessionStorage.removeItem(this.STATE_KEY);

    // Remove ?code= from the address bar so a refresh doesn't replay a used code.
    window.history.replaceState({}, document.title, window.location.pathname);

    if (!expectedState || params.get('state') !== expectedState) {
      this.showMessage(messageEl, 'Sign in failed (invalid state). Please try again.', 'error');
      return;
    }

    this.exchangeCodeForToken(code, messageEl);
  },

  // Step 4: trade the one-time code for tokens. This app client is public
  // (no client secret), which is the expected setup for a browser-only app.
  async exchangeCodeForToken(code, messageEl) {
    try {
      this.showMessage(messageEl, 'Authenticating...', '');

      const response = await fetch(`https://${this.cognitoDomain}/oauth2/token`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
        body: new URLSearchParams({
          grant_type: 'authorization_code',
          client_id: this.clientId,
          redirect_uri: this.redirectUri,
          code
        }).toString()
      });

      if (!response.ok) throw new Error('Token exchange failed');

      const data = await response.json();
      this.setToken(data.id_token);

      this.showMessage(messageEl, 'Sign in successful. Redirecting...', 'success');
      setTimeout(() => { window.location.href = './dashboard.html'; }, 1000);
    } catch (error) {
      console.error('Auth error:', error);
      this.showMessage(messageEl, 'Sign in failed. Please try again.', 'error');
    }
  },

  showMessage(el, text, type) {
    if (!el) return;
    el.textContent = text;
    el.className = type ? `auth-message ${type}` : 'auth-message';
  },

  logout() {
    localStorage.removeItem(this.TOKEN_KEY);
    window.location.href = './index.html';
  },

  /**
   * fetch() wrapper used by all editors. Adds the Bearer token, resolves the
   * URL against ADMIN_CONFIG.apiEndpoint, and logs out on 401 (expired token).
   * Returns the Response, or null if the user was sent back to login.
   */
  async request(path, options = {}) {
    const token = this.getToken();

    if (!token || !this.isTokenValid(token)) {
      window.location.href = './index.html';
      return null;
    }

    const headers = {
      'Authorization': `Bearer ${token}`,
      'Content-Type': 'application/json',
      ...options.headers
    };

    // Editors call paths like '/admin/api/content'; swap the prefix for the real API base URL.
    const url = path.startsWith('http') ? path : `${this.apiEndpoint}${path.replace('/admin/api', '')}`;

    const response = await fetch(url, { ...options, headers });

    if (response.status === 401) {
      this.logout();
      return null;
    }

    return response;
  }
};

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => AdminAuth.init());
} else {
  AdminAuth.init();
}
